const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');

function reader(route, { manyReferences = false } = {}) {
  const packParent = route === 'fetch' ? 2 : 3;
  const collections = [
    { _id: 1, title: 'Shower' },
    { _id: 2, title: 'Styles', parent: { $id: 1 } },
    { _id: 3, title: 'More styles', parent: { $id: 1 } },
    { _id: 4, title: 'Pack', parent: { $id: packParent } },
  ];
  const preview = { _id: 10, title: 'preview', excerpt: 'Prompt', tags: ['shower:no-cover'], cover: 'https://images.test/autogenerated', media: [{ link: 'https://images.test/fallback' }] };
  const refs = Array.from({ length: manyReferences ? 50 : 2 }, (_, i) => ({ _id: 20 + i, title: `reference-${i + 1}.png`, cover: `https://images.test/${i + 1}` }));
  const items = [preview, ...refs];
  const calls = [];
  const exports = {};
  const code = ts.transpileModule(fs.readFileSync(`src/app/api/raindrop/${route}/route.ts`, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  vm.runInNewContext(code, {
    exports, process: { env: {} }, console, setTimeout,
    require: name => {
      if (name === 'next/server') return { NextResponse: { json: (data, init = {}) => ({ data, status: init.status || 200 }) } };
      if (name === '@/lib/characterNote') return { getCharacterAddOns: () => [] };
      throw new Error(`Unexpected module ${name}`);
    },
    fetch: async url => {
      const parsed = new URL(url);
      calls.push(parsed.pathname + parsed.search);
      let data;
      if (parsed.pathname.endsWith('/collections')) data = { items: collections };
      else if (parsed.pathname.endsWith('/collections/childrens')) data = { items: [] };
      else if (parsed.pathname.endsWith('/raindrops/4')) {
        const page = Number(parsed.searchParams.get('page') || '0');
        data = { items: items.slice(page * 50, (page + 1) * 50) };
      } else if (parsed.pathname.endsWith('/raindrops/3')) data = { items: [{ _id: 99, title: 'Loose style', excerpt: 'Loose prompt', tags: ['shower:no-cover'], cover: 'https://images.test/loose-cover' }] };
      else data = { items: [] };
      return { ok: true, status: 200, json: async () => data };
    },
  });
  return { calls, read: () => exports.POST({ json: async () => ({ token: 'test-only' }), headers: new Headers() }) };
}

for (const route of ['fetch', 'more-styles']) {
  test(`${route}: removed covers stay absent after re-sync and all 50 references load`, async () => {
    const { read, calls } = reader(route, { manyReferences: true });
    const result = await read();
    assert.equal(result.status, 200);
    const pack = result.data.styles.find(style => style.id === 4);
    assert.equal(pack.preview_cover, '');
    assert.equal(pack.style_reference_links.length, 50);
    assert.equal(pack.style_reference_links[49], 'https://images.test/50');
    assert.equal(calls.some(url => url.endsWith('page=1')), true);
  });
}

test('more-styles: packs and loose styles remain visible together', async () => {
  const result = await reader('more-styles').read();
  assert.deepEqual(Array.from(result.data.styles, style => style.id), [4, 99]);
  assert.equal(result.data.styles[1].preview_cover, '');
});
